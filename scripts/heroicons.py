"""Writes src/components/admin/filament/heroicons.ts from the Laravel app's blade-heroicons
SVGs (MIT, the same files Filament renders). Add a name and run again to use another icon."""
import json, re, sys
SOURCE = "/home/cuncis/inofarma/vendor/blade-ui-kit/blade-heroicons/resources/svg"
NAMES = """o-bars-3 o-x-mark m-x-mark m-magnifying-glass o-bell o-bell-slash m-user-circle m-sun m-moon
m-computer-desktop m-arrow-left-on-rectangle o-home o-shopping-bag o-cube o-users o-chat-bubble-left-right
o-ticket o-envelope o-building-storefront o-user-group o-photo o-paint-brush o-lock-closed o-lock-open
o-check-circle o-exclamation-triangle o-x-circle o-information-circle m-chevron-right o-chevron-right
o-tag o-archive-box o-document-text o-qr-code o-banknotes o-shield-check o-arrows-right-left o-truck
o-arrow-top-right-on-square o-question-mark-circle o-receipt-refund o-building-office o-scale o-key
o-arrow-up-tray o-shield-exclamation o-table-cells o-arrow-path
c-eye c-pencil-square c-trash m-chevron-left m-ellipsis-vertical m-funnel m-trash o-check-badge
m-arrow-uturn-left m-arrow-left-end-on-rectangle c-x-mark o-trash o-arrow-uturn-left
m-view-columns m-arrows-up-down m-check m-bars-2 m-chevron-up m-chevron-down o-arrow-down-tray
o-shopping-cart o-inbox-arrow-down o-adjustments-horizontal o-plus
o-user-minus o-cog-6-tooth o-paper-airplane o-eye m-plus m-chevron-up-down o-arrow-down o-arrow-up""".split()
icons = {}
for name in NAMES:
    svg = open(f"{SOURCE}/{name}.svg").read()
    attrs = dict(re.findall(r'(\w[\w-]*)="([^"]*)"', re.search(r"<svg([^>]*)>", svg).group(1)))
    inner = re.sub(r"\s+", " ", svg[svg.index(">") + 1 : svg.rindex("</svg>")]).strip()
    icons[name] = {"viewBox": attrs.get("viewBox"), "fill": attrs.get("fill"), "stroke": attrs.get("stroke"), "strokeWidth": attrs.get("stroke-width"), "body": inner}
out = "// Generated by scripts/heroicons.py from blade-heroicons (MIT). Do not edit by hand.\n"
out += "export const HEROICONS: Record<string, { viewBox: string; fill: string | null; stroke: string | null; strokeWidth: string | null; body: string }> = "
out += json.dumps(icons, indent=1, ensure_ascii=False) + ";\n"
open("src/components/admin/filament/heroicons.ts", "w").write(out)
print(len(icons), "icons")
